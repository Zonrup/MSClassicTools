"""Download a sprite for every monster in data/victoria.js from meowDB.

    python tools/fetch_mob_images.py

Saves data/mobs/mob_<meowdbId>.<png|gif> (meowDB serves many as animated GIFs under a
.png name, so the extension comes from the file's own header) and writes
data/mob_images.js: window.MOB_IMAGES = { "<monster key>": "data/mobs/mob_7.gif", ... }.
Files already on disk are kept; delete one to fetch it again.
"""
import json
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
URL = "https://meowdb.com/msclassic/monsters/sprites/mob_{}.png"

txt = (ROOT / "data" / "victoria.js").read_text(encoding="utf-8")
data = json.loads(txt[txt.index("{", txt.index("window.WORLD_DATA")):txt.rindex("}") + 1])
out = ROOT / "data" / "mobs"
out.mkdir(exist_ok=True)


def kind(b):
    if b.startswith(b"\x89PNG"):
        return "png"
    if b.startswith(b"GIF8"):
        return "gif"
    if b[:4] == b"RIFF" and b[8:12] == b"WEBP":
        return "webp"
    return None


images, failed = {}, []
for key, mob in data["mobs"].items():
    mid = mob["meowdbId"]
    have = [p for p in out.glob(f"mob_{mid}.*") if p.stat().st_size]
    if have:
        images[key] = f"data/mobs/{have[0].name}"
        continue
    try:
        req = urllib.request.Request(URL.format(mid), headers={"User-Agent": "Mozilla/5.0 (world-map sprite fetch)"})
        with urllib.request.urlopen(req, timeout=20) as r:
            body = r.read()
        ext = kind(body)
        if not ext:
            raise ValueError(f"unknown image format ({len(body)} bytes)")
        (out / f"mob_{mid}.{ext}").write_bytes(body)
        images[key] = f"data/mobs/mob_{mid}.{ext}"
    except Exception as e:  # keep going; report at the end
        failed.append((mob["name"], mid, str(e)[:80]))
    time.sleep(0.3)  # be gentle with meowDB

(ROOT / "data" / "mob_images.js").write_text(
    "// Generated by tools/fetch_mob_images.py. Monster key -> sprite file.\n"
    "window.MOB_IMAGES = " + json.dumps(images, indent=1, sort_keys=True) + ";\n",
    encoding="utf-8")
print(f"images {len(images)} of {len(data['mobs'])} | failed {failed}")
