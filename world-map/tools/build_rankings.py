"""Build the default farming-spot rankings, data/rankings.js, from data/victoria.js.

    python3 tools/build_rankings.py

For each monster (by its picker name, so same-name variants at different levels are ranked
separately, e.g. "Zombie Mushroom" and "Zombie Mushroom (Lv 30)"), its maps are ranked by
the monster's share of the map's spawns: its spawn count divided by all monster spawns on
the map. Ties break by raw spawn count, then map name. Then:
  - a monster on only 1 or 2 maps: all of them are "best";
  - otherwise the top 15% of its maps (rounded up) are "best", the rest of the top 50%
    (rounded up) are "okay", and the bottom half are "meh".

The page lets people edit rankings (saved in their browser) and download them all as a
rankings.js file; dropping that file in data/ makes the edits the new packaged default.
"""
import json
import math
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "victoria.js"
OUT = ROOT / "data" / "rankings.js"
TIERS = ("best", "okay", "meh")


def load(path):
    t = path.read_text(encoding="utf-8")
    return json.loads(t[t.index("{"):t.rindex("}") + 1])


def entries(m):
    for e in m.get("mobs") or []:
        yield (e, None) if isinstance(e, str) else (e["id"], e.get("count"))


def mob_labels(data):
    """Monster id -> picker name. Must match mobLabels() in js/map.js: when several
    monsters share a name, the one on the most maps keeps it and the others get " (Lv N)"."""
    on = defaultdict(set)
    for m in data["maps"]:
        for mid, _ in entries(m):
            on[mid].add(m["id"])
    by_name = defaultdict(list)
    for mid, mob in data["mobs"].items():
        by_name[mob["name"]].append(mid)
    out = {}
    for name, ids in by_name.items():
        ids.sort(key=lambda i: (-len(on[i]), data["mobs"][i].get("level", 0), i))
        for k, mid in enumerate(ids):
            out[mid] = name if k == 0 else f"{name} (Lv {data['mobs'][mid].get('level', 0)})"
    return out


def build(data):
    label = mob_labels(data)
    # monster name -> map id -> spawn count; and map id -> total spawns
    counts = defaultdict(lambda: defaultdict(int))
    totals = {}
    names = {m["id"]: m["name"] for m in data["maps"]}
    for m in data["maps"]:
        tot = 0
        for mid, c in entries(m):
            if mid not in data["mobs"]:
                continue
            c = c or 1  # an entry without a count counts as one spawn
            counts[label[mid]][m["id"]] += c
            tot += c
        totals[m["id"]] = tot
    out = {}
    for mob in sorted(counts):
        ranked = sorted(counts[mob].items(),
                        key=lambda kv: (-kv[1] / totals[kv[0]], -kv[1], names[kv[0]]))
        ids = [k for k, _ in ranked]
        n = len(ids)
        if n <= 2:
            best, okay = n, n
        else:
            best, okay = max(1, math.ceil(n * 0.15)), math.ceil(n * 0.5)
        out[mob] = {"best": ids[:best], "okay": ids[best:okay], "meh": ids[okay:]}
    return out


def write(rankings, path=OUT):
    path.write_text(
        "// Default farming-spot rankings: monster name -> map ids per tier, best first.\n"
        "// Generated by tools/build_rankings.py; can be replaced by the page's \"Download all rankings\".\n"
        "window.MAP_RANKINGS = " + json.dumps(rankings, indent=1, ensure_ascii=False) + ";\n",
        encoding="utf-8")


if __name__ == "__main__":
    r = build(load(SRC))
    write(r)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(r)} monsters, "
          + ", ".join(f"{sum(len(v[t]) for v in r.values())} {t}" for t in TIERS))
